'use client';

/**
 * RouteErrorBoundary
 *
 * A React class component error boundary that catches rendering and lifecycle
 * errors at the route level. It surfaces a user-friendly recovery UI and
 * exposes a "Try again" button that clears the error and forces a re-render.
 *
 * Security invariant: NO wallet secrets, signed XDR envelopes, or private-key
 * material are stored in `state.errorInfo` or propagated anywhere outside this
 * component. The captured `componentStack` contains only component-name strings
 * produced by React's internal fiber tree and is safe to log.
 *
 * Issue #404 — route error recovery for dashboard and transaction pages.
 */

import React, { Component, ErrorInfo, ReactNode } from 'react';
import { AlertTriangle, RefreshCw } from 'lucide-react';

interface Props {
  /** Child subtree to protect (the route page component). */
  children: ReactNode;
  /**
   * Human-readable name for this boundary, shown in the fallback UI.
   * E.g. "Dashboard" or "Transactions".
   */
  routeName?: string;
}

interface State {
  /** Whether an unrecovered error is currently active. */
  hasError: boolean;
  /**
   * Display-safe error message derived from the thrown value.
   * Never contains wallet secrets or signed envelopes — only
   * `Error.message` / stringified non-Error values, which are always
   * generated by application code or the network layer, not by Freighter.
   */
  displayMessage: string;
  /**
   * React component stack for internal diagnostics.
   * Contains component-name strings only — no runtime secrets.
   */
  componentStack: string;
}

/**
 * Converts an unknown thrown value into a display-safe string.
 *
 * - `Error` instances: uses `.message` only (never `.stack`, which can
 *   contain file paths that look sensitive to end users).
 * - Other values: converts to a short string representation.
 *
 * In no case does this function expose wallet secret keys, signed XDR
 * envelopes, or other sensitive credential material because such values are
 * never stored in React state (see `ActionModal` — signing happens inside a
 * try/catch that only surfaces a generic failure message to state).
 */
function toDisplayMessage(error: unknown): string {
  if (error instanceof Error) {
    return error.message || 'An unexpected error occurred.';
  }
  try {
    return String(error) || 'An unexpected error occurred.';
  } catch {
    return 'An unexpected error occurred.';
  }
}

export class RouteErrorBoundary extends Component<Props, State> {
  constructor(props: Props) {
    super(props);
    this.state = {
      hasError: false,
      displayMessage: '',
      componentStack: '',
    };
  }

  /** Called by React when any child throws during rendering. */
  static getDerivedStateFromError(error: unknown): Partial<State> {
    return {
      hasError: true,
      displayMessage: toDisplayMessage(error),
    };
  }

  /** Captures the component stack for diagnostics (no secrets). */
  componentDidCatch(error: unknown, info: ErrorInfo): void {
    this.setState({ componentStack: info.componentStack ?? '' });
    // Only log to console in development; a real app would send to an
    // observability backend (no PII or secret values are present here).
    if (process.env.NODE_ENV === 'development') {
      // eslint-disable-next-line no-console
      console.error('[RouteErrorBoundary]', error, info.componentStack);
    }
  }

  /** Clears the error state so the child tree is remounted. */
  private handleRetry = (): void => {
    this.setState({
      hasError: false,
      displayMessage: '',
      componentStack: '',
    });
  };

  render(): ReactNode {
    if (!this.state.hasError) {
      return this.props.children;
    }

    const routeName = this.props.routeName ?? 'this page';

    return (
      <div
        role="alert"
        aria-live="assertive"
        className="min-h-screen bg-[#080b11] text-slate-100 flex items-center justify-center px-4"
      >
        <div className="max-w-md w-full rounded-2xl border border-red-500/30 bg-red-950/20 p-8 text-center shadow-xl">
          {/* Icon */}
          <div className="mx-auto mb-4 flex h-16 w-16 items-center justify-center rounded-full bg-red-500/10 border border-red-500/30">
            <AlertTriangle size={32} className="text-red-400" aria-hidden="true" />
          </div>

          {/* Heading */}
          <h2 className="mb-2 text-xl font-bold text-white">
            {routeName} unavailable
          </h2>

          {/* User-facing message */}
          <p className="mb-2 text-sm text-slate-400 leading-relaxed">
            Something went wrong while loading {routeName.toLowerCase()}.
            Your funds are safe — this is a display error only.
          </p>

          {/* Display-safe technical detail — never contains secrets */}
          {this.state.displayMessage && (
            <p className="mb-6 rounded-lg border border-slate-700 bg-slate-900 px-3 py-2 font-mono text-xs text-slate-400 text-left break-words">
              {this.state.displayMessage}
            </p>
          )}

          {/* Retry button — remounts the failed subtree */}
          <button
            onClick={this.handleRetry}
            className="inline-flex items-center gap-2 rounded-xl bg-gradient-to-r from-emerald-500 to-teal-600 px-6 py-3 font-bold text-slate-950 shadow-glow-emerald transition-all hover:from-emerald-400 hover:to-teal-500 focus:outline-none focus:ring-2 focus:ring-emerald-500 focus:ring-offset-2 focus:ring-offset-slate-950"
            aria-label={`Retry loading ${routeName}`}
          >
            <RefreshCw size={16} aria-hidden="true" />
            Try again
          </button>
        </div>
      </div>
    );
  }
}
